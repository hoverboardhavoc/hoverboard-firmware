//! The HAL side: every vector body for one chip, compiled into one thumbv7m image against
//! `motorcontroller/hal` with that chip's feature.
//!
//! The image is a generated crate under the build directory: each vector body becomes a module, and
//! an exported `gt_<area>__<name>` function calls its `body()`. It links like an image does
//! (cortex-m-rt's `link.x`, the HAL's flash vector table), with a `main` that names every entry so
//! the link keeps them; the emulator calls each entry directly. The crate builds against the
//! versions `motorcontroller/Cargo.lock` pins.

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::vector::{HalSide, Vector};

/// The entry function of a vector in the HAL image.
pub fn entry(id: &str) -> String {
    format!("gt_{}", id.replace('/', "__"))
}

const BUILD_RS: &str = r#"// Generated by golden-trace. The memory map the emulator gives every chip, and cortex-m-rt's link.
fn main() {
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    std::fs::write(
        out.join("memory.x"),
        "MEMORY\n{\n  FLASH : ORIGIN = 0x08000000, LENGTH = 256K\n  RAM : ORIGIN = 0x20000000, LENGTH = 64K\n}\n",
    )
    .unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rustc-link-arg-bins=-Tlink.x");
}
"#;

fn manifest(chip: &str, hal_dir: &Path) -> String {
    format!(
        r#"# Generated by golden-trace: the HAL vector bodies for {chip}.
[package]
name = "golden-trace-hal-{chip}"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
hal = {{ path = "{hal}", features = ["{chip}"] }}
cortex-m-rt = "0.7"
heapless = "0.8"

[profile.release]
opt-level = "s"
lto = true
codegen-units = 1
panic = "abort"
debug = false
strip = false

[workspace]
"#,
        hal = hal_dir.display()
    )
}

fn main_rs(chip: &str, vectors: &[&Vector]) -> String {
    let mut s = format!(
        "// Generated by golden-trace: the HAL vector bodies for {chip}.\n\
         #![no_std]\n#![no_main]\n#![allow(unused_imports)]\n\n\
         #[panic_handler]\nfn panic(_: &core::panic::PanicInfo) -> ! {{\n    loop {{}}\n}}\n\n"
    );
    let mut entries = Vec::new();
    for v in vectors {
        let HalSide::Body(body) = &v.hal else {
            continue;
        };
        let e = entry(&v.id);
        let module = format!("v_{}", v.id.replace('/', "__"));
        s.push_str(&format!(
            "/// vectors/{id}.toml\nmod {module} {{\n{body}}}\n\n\
             #[no_mangle]\npub extern \"C\" fn {e}() {{\n    {module}::body();\n}}\n\n",
            id = v.id
        ));
        entries.push(e);
    }
    s.push_str(&format!(
        "/// Never run: the emulator calls each entry directly. Naming them here keeps them linked.\n\
         #[cortex_m_rt::entry]\nfn main() -> ! {{\n    let entries: [extern \"C\" fn(); {n}] = [{list}];\n    \
         core::hint::black_box(entries);\n    loop {{}}\n}}\n",
        n = entries.len(),
        list = entries.join(", ")
    ));
    s
}

fn write_if_changed(path: &Path, text: &str) -> Result<(), String> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(text) {
        return Ok(());
    }
    std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Build the HAL image for `chip` holding every vector in `vectors` that has a HAL body, and return
/// the ELF's path.
pub fn build(
    repo: &Path,
    build: &Path,
    chip: &str,
    vectors: &[&Vector],
) -> Result<PathBuf, String> {
    let crate_dir = build.join(format!("hal-{chip}"));
    std::fs::create_dir_all(crate_dir.join("src")).map_err(|e| e.to_string())?;
    let hal_dir = repo.join("motorcontroller/hal");
    write_if_changed(&crate_dir.join("Cargo.toml"), &manifest(chip, &hal_dir))?;
    write_if_changed(&crate_dir.join("build.rs"), BUILD_RS)?;
    write_if_changed(&crate_dir.join("src/main.rs"), &main_rs(chip, vectors))?;
    // The versions the images build with.
    let lock = std::fs::read_to_string(repo.join("motorcontroller/Cargo.lock"))
        .map_err(|e| format!("motorcontroller/Cargo.lock: {e}"))?;
    write_if_changed(&crate_dir.join("Cargo.lock"), &lock)?;

    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let target_dir = build.join("cargo");
    let out = Command::new(&cargo)
        .current_dir(&crate_dir)
        .args(["build", "--release", "--target", "thumbv7m-none-eabi"])
        .env("CARGO_TARGET_DIR", &target_dir)
        .output()
        .map_err(|e| format!("{cargo}: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "the HAL image for {chip} did not build:\n{}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(target_dir
        .join("thumbv7m-none-eabi/release")
        .join(format!("golden-trace-hal-{chip}")))
}
